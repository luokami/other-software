const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','preview','--host','127.0.0.1','--port','4173','--strictPort'],{stdio:['ignore','pipe','inherit']});
(async()=>{
 await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('Preview server timeout')),15000);server.stdout.on('data',data=>{if(data.toString().includes('4173')){clearTimeout(timer);resolve()}});server.on('exit',code=>{clearTimeout(timer);reject(Error('Preview server exited: '+code))})});
 fs.mkdirSync('build',{recursive:true});
 const browser=await chromium.launch({headless:true});
 const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
 await context.addInitScript(()=>{
  let revision=-1,book={name:'测试店铺',entries:[],loans:[],categories:[],reminders:[]};
  window.Native={readBook:()=>JSON.stringify({book,revision}),saveBook:(text,expected)=>{if(expected!==revision)return JSON.stringify({error:'版本冲突'});book=JSON.parse(text);return JSON.stringify({revision:++revision})},readRecovery:()=>'',exportFile:()=>'{}',chooseBackup:()=>'{}'};
 });
 const page=await context.newPage();const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/');
 const guide=page.getByRole('dialog');
 await page.getByRole('heading',{name:'从首页，记好第一笔'}).waitFor();
 assert.equal(JSON.parse(await page.evaluate(()=>window.Native.readBook())).book.entries.length,0);
 await page.getByRole('button',{name:'下一步',exact:true}).click();
 await page.getByRole('heading',{name:'借出去的钱，单独记'}).waitFor();
 await page.getByRole('button',{name:'上一步',exact:true}).click();
 await page.getByRole('heading',{name:'从首页，记好第一笔'}).waitFor();
 for(let i=0;i<3;i++)await page.getByRole('button',{name:'下一步',exact:true}).click();
 await page.getByRole('heading',{name:'备份好，再放心用'}).waitFor();
 await page.getByRole('button',{name:'开始使用',exact:true}).click();
 await guide.waitFor({state:'hidden'});
 await page.reload();await page.getByRole('heading',{name:'小店账本',exact:true}).waitFor();
 assert.equal(await guide.count(),0,'Completed guide must not reopen');
 assert.equal(await page.evaluate(()=>localStorage.getItem('ledger-first-use-guide-v1')),'seen');
 const header=await page.getByRole('heading',{name:'小店账本',exact:true}).boundingBox();
 assert(header.y>=24,'Home header must retain top spacing');
 await page.getByRole('tab',{name:'设置',exact:true}).click();
 await page.getByRole('button',{name:'使用教程',exact:true}).click();
 await page.getByRole('heading',{name:'从首页，记好第一笔'}).waitFor();
 assert.equal(await page.evaluate(()=>window.ledgerHandleBack()),true);
 await guide.waitFor({state:'hidden'});
 await page.getByRole('button',{name:'特大',exact:true}).click();
 await page.getByRole('tab',{name:'深色模式',exact:true}).click();
 for(const size of [{width:320,height:568},{width:844,height:390},{width:390,height:700}]){
  await page.setViewportSize(size);
  await page.getByRole('button',{name:'使用教程',exact:true}).click();
  await guide.waitFor();
  const box=await guide.boundingBox();
  assert(box.x>=10&&box.y>=10&&box.x+box.width<=size.width-10&&box.y+box.height<=size.height-10,JSON.stringify({size,box}));
  const overflow=await guide.evaluate(el=>el.scrollWidth>el.clientWidth+1);
  assert(!overflow,'Guide should not overflow horizontally');
  const next=await page.getByRole('button',{name:'下一步',exact:true}).boundingBox();
  assert(next.y+next.height<=size.height-10,'Controls remain visible at largest font');
  await page.screenshot({path:path.join('build',`guide-${size.width}x${size.height}.png`)});
  await page.getByRole('button',{name:'关闭使用教程'}).click();
 }
 await page.evaluate(()=>localStorage.removeItem('ledger-first-use-guide-v1'));
 await page.reload();await page.getByRole('button',{name:'稍后再看',exact:true}).click();
 await page.reload();await page.getByRole('heading',{name:'小店账本',exact:true}).waitFor();
 assert.equal(await guide.count(),0,'Skipping should persist');
 assert.deepEqual(errors,[]);
 console.log('PASS: first launch, all steps, previous/next, complete/skip persistence, settings replay, native Back, unchanged book and three small/landscape viewports at largest font.');
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>server.kill());
